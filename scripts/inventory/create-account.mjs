#!/usr/bin/env node
// ============================================================================
// Create the ONE inventory account (role `inventory`, migration 0027) the
// same way every fixed account was created: an auth.users row made by the
// database owner (no sign-up, no recovery), its profile, and a bcrypt PIN
// set through public.set_account_pin() (0014), whose login goes through
// pin_login_attempt() with the same lockout as everyone else.
//
//   node scripts/inventory/create-account.mjs              # create if missing
//   node scripts/inventory/create-account.mjs --reset-pin  # also (re)set the PIN of the existing inventory account
//
// Reads INVENTORY_USERNAME and INVENTORY_PIN from .env.local (or the env
// file in INVENTORY_ENV_FILE). If either is missing, it generates one (a
// random 6-digit PIN with no repeated digits and no runs like 1-2-3) and
// writes it to that env file ONLY. This file contains no account values and
// never prints them. Runs on the live project with SUPABASE_ACCESS_TOKEN +
// SUPABASE_PROJECT_REF (Management API).
//
// Touches no other account: if the username belongs to any account that
// isn't the inventory account, it stops without changing anything.
// ============================================================================
import { appendFileSync, readFileSync } from "node:fs";
import { randomInt } from "node:crypto";
import { loadEnv, managementQuery } from "./lib.mjs";

const RESET = process.argv.includes("--reset-pin");
const env = loadEnv();

/** 6 digits, all different, no two neighbours one apart (no 12, 21, 89 …). */
export function goodPin(pin) {
  if (!/^\d{6}$/.test(pin)) return false;
  if (new Set(pin).size !== 6) return false;
  for (let i = 1; i < 6; i++) if (Math.abs(Number(pin[i]) - Number(pin[i - 1])) === 1) return false;
  return true;
}
function newPin() {
  for (;;) {
    const p = String(randomInt(0, 1_000_000)).padStart(6, "0");
    if (goodPin(p)) return p;
  }
}

let username = env.get("INVENTORY_USERNAME").trim().toLowerCase();
let pin = env.get("INVENTORY_PIN").trim();
const generated = [];
if (!username) {
  username = "inventory1";
  generated.push(`INVENTORY_USERNAME=${username}`);
}
if (!pin) {
  pin = newPin();
  generated.push(`INVENTORY_PIN=${pin}`);
}
if (!/^[a-z0-9_]{2,32}$/.test(username)) {
  console.error("INVENTORY_USERNAME must be 2–32 characters: a–z, 0–9 and _.");
  process.exit(1);
}
if (!goodPin(pin)) {
  console.error("INVENTORY_PIN must be 6 different digits, without runs like 1-2-3.");
  process.exit(1);
}
if (generated.length) {
  const text = readFileSync(env.file, "utf8");
  appendFileSync(env.file, `${text.endsWith("\n") ? "" : "\n"}\n# Inventory login (generated by scripts/inventory/create-account.mjs). Never commit.\n${generated.join("\n")}\n`);
  console.log(`Generated ${generated.map((g) => g.split("=")[0]).join(" and ")} and saved ${generated.length === 1 ? "it" : "them"} in ${env.file} only.`);
}

// username and PIN are checked above (only [a-z0-9_] and digits), so they can sit in SQL literals
const sql = accountSql(username, pin, RESET);

/** The account SQL (exported for the local rehearsal test). */
export function accountSql(username, pin, reset) {
  if (!/^[a-z0-9_]{2,32}$/.test(username) || !/^\d{6}$/.test(pin)) throw new Error("bad account values");
  return `
begin;
do $$
declare
  v_id   uuid;
  v_role text;
  uid    uuid;
begin
  select id, role::text into v_id, v_role from public.profiles where username = '${username}';
  if v_id is not null and v_role <> 'inventory' then
    raise exception 'that username belongs to another account: nothing changed';
  end if;
  if v_id is null then
    uid := gen_random_uuid();
    insert into auth.users (
      id, instance_id, aud, role, email, encrypted_password,
      email_confirmed_at, last_sign_in_at,
      raw_app_meta_data, raw_user_meta_data,
      created_at, updated_at,
      confirmation_token, email_change, email_change_token_new, recovery_token
    )
    values (
      uid, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated',
      '${username}@nr.local',
      crypt(encode(gen_random_bytes(32), 'hex'), gen_salt('bf')),
      now(), null,
      '{"provider":"email","providers":["email"]}'::jsonb,
      jsonb_build_object('username', '${username}', 'full_name', 'Inventory', 'role', 'inventory'),
      now(), now(), '', '', '', ''
    );
    insert into auth.identities (id, user_id, provider_id, identity_data, provider,
                                 last_sign_in_at, created_at, updated_at)
    values (gen_random_uuid(), uid, uid::text,
            jsonb_build_object('sub', uid::text, 'email', '${username}@nr.local', 'email_verified', true),
            'email', null, now(), now());
    update public.profiles
       set username = '${username}', full_name = 'Inventory', role = 'inventory'
     where id = uid;
    perform public.set_account_pin('${username}', '${pin}');
    raise notice 'created';
  elsif ${reset ? "true" : "false"} then
    perform public.set_account_pin('${username}', '${pin}');
  end if;
end $$;
commit;
select count(*)::int as inventory_accounts,
       count(*) filter (where ap.profile_id is not null)::int as with_pin
  from public.profiles p left join public.account_pins ap on ap.profile_id = p.id
 where p.role::text = 'inventory';
`;
}

try {
  const rows = await managementQuery(env, sql);
  const r = rows[0] ?? {};
  console.log(`Inventory accounts: ${r.inventory_accounts}, with a PIN: ${r.with_pin}.${RESET ? " PIN (re)set." : ""}`);
} catch (e) {
  // never echo the SQL (it holds the PIN)
  console.error(String(e.message).replace(/\d{6}/g, "******"));
  process.exit(1);
}
